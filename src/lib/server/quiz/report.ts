// quiz-report.md: a summary of every quiz for checking progress towards the
// content targets. Written to the repo root by `npm run build` and
// `npm run dev`. It is never published, and git ignores it.

import { TARGET_REVIEWED_EXAM_SKILLS, TARGET_REVIEWED_QUESTIONS } from '../config';
import { inContext } from './warnings';
import type { Quiz } from './types';

function counts(values: string[]): string {
	const tally = new Map<string, number>();
	for (const v of values) tally.set(v, (tally.get(v) ?? 0) + 1);
	return [...tally].sort().map(([k, n]) => `${k} ${n}`).join(', ') || 'none';
}

export function quizReport(quizzes: Quiz[], warnings: string[]): string {
	const lines = [
		'# Quiz report',
		'',
		'Generated by the build from content/quizzes/. Not published; don\'t edit by hand.',
		''
	];

	for (const quiz of quizzes) {
		const qs = quiz.questions;
		const reviewed = qs.filter((q) => q.status === 'reviewed');
		const skills = qs.filter((q) => q.type === 'exam_skill');
		const reviewedConcepts = new Set(reviewed.filter((q) => q.type !== 'exam_skill').map((q) => q.concept));
		const noSee = qs.filter((q) => !q.see).map((q) => q.id);
		const reviewedSkills = reviewed.filter((q) => q.type === 'exam_skill').length;

		lines.push(
			`## ${quiz.topic} (\`${quiz.id}\`)`,
			'',
			`Page: ${quiz.page}`,
			'',
			'| | |',
			'|---|---|',
			`| Questions | ${qs.length} (${counts(qs.map((q) => q.status))}) |`,
			`| By type | ${counts(qs.map((q) => q.type))} |`,
			`| exam_skill formats | ${counts(skills.map((q) => (q.type === 'exam_skill' ? q.format : '')))} |`,
			`| Command words | ${counts(qs.map((q) => q.command))} |`,
			`| In a product context | ${qs.filter(inContext).length} of ${qs.length} (${Math.round((qs.filter(inContext).length / qs.length) * 100)}%) |`,
			`| Calculation questions | ${qs.filter((q) => q.command === 'calculate' && q.type !== 'exam_skill').length} |`,
			`| Reviewed concepts | ${reviewedConcepts.size} (an attempt draws up to ${quiz.questions_per_attempt}) |`,
			`| Without a "see" link | ${noSee.length ? noSee.join(', ') : 'none'} |`,
			`| To reach the target | ${Math.max(0, TARGET_REVIEWED_QUESTIONS - reviewed.length)} more reviewed questions, ${Math.max(0, TARGET_REVIEWED_EXAM_SKILLS - reviewedSkills)} more reviewed exam_skill questions |`,
			''
		);
	}

	lines.push('## Warnings', '');
	lines.push(...(warnings.length ? warnings.map((w) => `- ${w}`) : ['None.']), '');
	return lines.join('\n');
}
